package main

import (
"fmt"
"log"
"os"

"gorm.io/driver/postgres"
"gorm.io/gorm"
"gorm.io/gorm/logger"
)

func main() {
db, err := gorm.Open(postgres.Open("host=localhost user=postgres password=postgres dbname=sistem_akuntansi port=5432 sslmode=disable"), &gorm.Config{
Logger: logger.Default.LogMode(logger.Silent),
})
if err != nil {
log.Fatal(err)
}

f, _ := os.Create("C:\\temp\\diag5.txt")
defer f.Close()

w := func(format string, args ...interface{}) { fmt.Fprintf(f, format+"\n", args...) }

// Check unified_journal_ledgers for J#7
type JL struct {
ID uint; JournalType string; SourceType string; SourceID *uint; Reference string; Description string; Status string; IsAutoGenerated bool
}
var jls []JL
db.Raw("SELECT id, journal_type, source_type, source_id, reference, description, status, is_auto_generated FROM unified_journal_ledgers WHERE id = 7").Scan(&jls)
w("== Journal Ledger #7 ==")
for _, j := range jls {
sid := "nil"
if j.SourceID != nil { sid = fmt.Sprintf("%d", *j.SourceID) }
w("  ID=%d Type=%s SourceType=%s SourceID=%s Ref=%s Status=%s AutoGen=%v | %s", 
j.ID, j.JournalType, j.SourceType, sid, j.Reference, j.Status, j.IsAutoGenerated, j.Description)
}

// Check SSOTJournalEntry table  
w("\n== ssot_journal_entries (all) ==")
type SJ struct {
ID uint; SourceType string; SourceID *uint; Reference string; Description string; Status string
}
var sjs []SJ
db.Raw("SELECT id, source_type, source_id, reference, description, status FROM ssot_journal_entries WHERE deleted_at IS NULL ORDER BY id").Scan(&sjs)
for _, s := range sjs {
sid := "nil"
if s.SourceID != nil { sid = fmt.Sprintf("%d", *s.SourceID) }
w("  ID=%d SourceType=%s SourceID=%s Ref=%s Status=%s | %s",
s.ID, s.SourceType, sid, s.Reference, s.Status, s.Description)
}

// Check if there are any simple_ssot_journals
w("\n== simple_ssot_journals ==")
type SSJ struct {
ID uint; Status string; Reference string; Description string
}
var ssjs []SSJ
db.Raw("SELECT id, status, reference, description FROM simple_ssot_journals ORDER BY id").Scan(&ssjs)
for _, s := range ssjs {
w("  ID=%d Status=%s Ref=%s | %s", s.ID, s.Status, s.Reference, s.Description)
}

// Check journal_entries (legacy)
w("\n== journal_entries (legacy) ==")
type JE struct {
ID uint; ReferenceType string; ReferenceID *uint; Reference string; Description string; Status string; TotalDebit float64; TotalCredit float64
}
var jes []JE
db.Raw("SELECT id, reference_type, reference_id, reference, description, status, total_debit, total_credit FROM journal_entries WHERE deleted_at IS NULL ORDER BY id").Scan(&jes)
for _, j := range jes {
rid := "nil"
if j.ReferenceID != nil { rid = fmt.Sprintf("%d", *j.ReferenceID) }
w("  JE#%d RefType=%s RefID=%s Ref=%s Status=%s D:%.2f C:%.2f | %s",
j.ID, j.ReferenceType, rid, j.Reference, j.Status, j.TotalDebit, j.TotalCredit, j.Description)
}

// Check payments table
w("\n== payments ==")
type Pay struct {
ID uint; Code string; Amount float64; Status string; Method string; ContactID uint; JournalEntryID *uint; PaymentType string; Notes string
}
var pays []Pay
db.Raw("SELECT id, code, amount, status, method, contact_id, journal_entry_id, payment_type, notes FROM payments WHERE deleted_at IS NULL ORDER BY id").Scan(&pays)
for _, p := range pays {
jid := "nil"
if p.JournalEntryID != nil { jid = fmt.Sprintf("%d", *p.JournalEntryID) }
w("  PAY#%d Code=%s Amount=%.2f Status=%s Method=%s Type=%s JID=%s Contact=%d | %s",
p.ID, p.Code, p.Amount, p.Status, p.Method, p.PaymentType, jid, p.ContactID, p.Notes)
}

w("\nDone")
}
