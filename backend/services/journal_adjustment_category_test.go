func TestJournalAdjustmentCategoriesMatchClientScope(t *testing.T) {
	categories := models.GetJournalAdjustmentCategories()
	if len(categories) != 5 {
		t.Fatalf("expected exactly 5 client-approved adjustment categories, got %d", len(categories))
	}

	expectedCodes := []string{
		models.JournalAdjustmentCategoryPPh21Accrual,
		models.JournalAdjustmentCategoryPPh23Accrual,
		models.JournalAdjustmentCategorySalesRevenueRecognition,
		models.JournalAdjustmentCategoryCOGSHPPRecognition,
		models.JournalAdjustmentCategoryPrepaidMonthlyRealization,
	}

	for _, expectedCode := range expectedCodes {
		category, exists := models.GetJournalAdjustmentCategory(expectedCode)
		if !exists {
			t.Fatalf("expected category %s to exist", expectedCode)
		}
		if strings.TrimSpace(category.COA) == "" {
			t.Fatalf("expected category %s to include COA mapping", expectedCode)
		}
	}
}

