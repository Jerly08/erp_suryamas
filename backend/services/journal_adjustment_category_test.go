func TestJournalAdjustmentCategoriesMatchClientScope(t *testing.T) {
	categories := models.GetJournalAdjustmentCategories()
	if len(categories) != 5 {
		t.Fatalf("expected exactly 5 client-approved adjustment categories, got %d", len(categories))
	}

	expectedCodes := []string{
		models.JournalAdjustmentCategoryPPh21Accrual,
		models.JournalAdjustmentCategoryPPh23Accrual,
		models.JournalAdjustmentCategorySalesRevenueRecognition,
		models.JournalAdjustmentCategoryCOGSHPPRecognition,
		models.JournalAdjustmentCategoryPrepaidMonthlyRealization,
	}

	for _, expectedCode := range expectedCodes {
		category, exists := models.GetJournalAdjustmentCategory(expectedCode)
		if !exists {
			t.Fatalf("expected category %s to exist", expectedCode)
		}
		if strings.TrimSpace(category.COA) == "" {
			t.Fatalf("expected category %s to include COA mapping", expectedCode)
		}
	}
}

func TestCreateJournalAdjustmentRequiresMappedCategory(t *testing.T) {
	db, err := gorm.Open(sqlite.Open("file:"+t.Name()+"?mode=memory&cache=shared"), &gorm.Config{})
	if err != nil {
		t.Fatalf("open sqlite db: %v", err)
	}

	if err := db.AutoMigrate(&models.Account{}, &models.AccountingPeriod{}, &models.CashBank{}, &models.SSOTJournalEntry{}, &models.SSOTJournalLine{}); err != nil {
		t.Fatalf("auto migrate: %v", err)
	}

	if err := db.Create(&[]models.Account{
		{
			ID:       1,
			Code:     "5101",
			Name:     "HPP",
			Type:     models.AccountTypeExpense,
			Category: models.CategoryCostOfGoodsSold,
			IsActive: true,
		},
		{
			ID:       2,
			Code:     "2103-009",
			Name:     "Estimated HPP Backorder",
			Type:     models.AccountTypeLiability,
			Category: models.CategoryCurrentLiability,
			IsActive: true,
		},
	}).Error; err != nil {
		t.Fatalf("seed accounts: %v", err)
	}

	original := models.SSOTJournalEntry{
		EntryNumber:     "JE-ORIGINAL",
		SourceType:      models.SSOTSourceTypeSale,
		EntryDate:       time.Date(2026, 5, 1, 0, 0, 0, 0, time.UTC),
		Description:     "Original sale journal",
		Reference:       "SOA-TEST",
		TotalDebit:      decimal.NewFromInt(1000),
		TotalCredit:     decimal.NewFromInt(1000),
		Status:          models.SSOTStatusPosted,
		IsBalanced:      true,
		IsAutoGenerated: true,
		CreatedBy:       1,
	}
	if err := db.Create(&original).Error; err != nil {
		t.Fatalf("create original journal: %v", err)
	}

	service := NewUnifiedJournalService(db)
	adjustmentOf := original.ID
	request := &JournalEntryRequest{
		EntryDate:    time.Date(2026, 5, 2, 0, 0, 0, 0, time.UTC),
		Reference:    "ADJ-SOA-TEST",
		Description:  "Adjust HPP variance",
		SourceType:   models.SSOTSourceTypeAdjustment,
		AdjustmentOf: &adjustmentOf,
		CreatedBy:    1,
		Lines: []JournalLineRequest{
			{
				AccountID:   1,
				DebitAmount: decimal.NewFromInt(100),
				Description: "Debit variance",
			},
			{
				AccountID:    2,
				CreditAmount: decimal.NewFromInt(100),
				Description:  "Credit clearing",
			},
		},
	}

	_, err = service.CreateJournalEntry(request)
	if err == nil || !strings.Contains(err.Error(), "kategori transaksi adjustment wajib dipilih") {
		t.Fatalf("expected missing category error, got %v", err)
	}

	request.AdjustmentCategoryCode = models.JournalAdjustmentCategorySalesBackorderHPP
	entry, err := service.CreateJournalEntry(request)
	if err != nil {
		t.Fatalf("create adjustment with category: %v", err)
	}

	if entry.Status != models.SSOTStatusDraft {
		t.Fatalf("expected adjustment to wait for approval as DRAFT, got %s", entry.Status)
	}
	if entry.ApprovalStage != models.SSOTApprovalStageFinanceManager {
		t.Fatalf("expected finance manager approval stage, got %s", entry.ApprovalStage)
	}
	if entry.AdjustmentCategoryCode != models.JournalAdjustmentCategorySalesBackorderHPP {
		t.Fatalf("expected category code to be persisted, got %s", entry.AdjustmentCategoryCode)
	}
	if entry.AdjustmentCategoryLabel == "" {
		t.Fatal("expected category label to be persisted")
	}
}

func TestJournalAdjustmentRequirementFilterUsesClientMapping(t *testing.T) {
	db, err := gorm.Open(sqlite.Open("file:"+t.Name()+"?mode=memory&cache=shared"), &gorm.Config{})
	if err != nil {
		t.Fatalf("open sqlite db: %v", err)
	}

	if err := db.AutoMigrate(&models.Account{}, &models.AccountingPeriod{}, &models.CashBank{}, &models.SSOTJournalEntry{}, &models.SSOTJournalLine{}); err != nil {
		t.Fatalf("auto migrate: %v", err)
	}

	accounts := []models.Account{
		{
			ID:       10,
			Code:     "1102-001",
			Name:     "Piutang Usaha",
			Type:     models.AccountTypeAsset,
			Category: models.CategoryCurrentAsset,
			IsActive: true,
		},
		{
			ID:       11,
			Code:     "4101",
			Name:     "Pendapatan Sales",
			Type:     models.AccountTypeRevenue,
			Category: models.CategoryOperatingRevenue,
			IsActive: true,
		},
		{
			ID:       12,
			Code:     "5101",
			Name:     "Beban Operasional",
			Type:     models.AccountTypeExpense,
			Category: models.CategoryOperatingExpense,
			IsActive: true,
		},
		{
			ID:       13,
			Code:     "2101",
			Name:     "Utang Usaha",
			Type:     models.AccountTypeLiability,
			Category: models.CategoryCurrentLiability,
			IsActive: true,
		},
	}
	if err := db.Create(&accounts).Error; err != nil {
		t.Fatalf("seed accounts: %v", err)
	}

	createJournal := func(entryNumber, sourceType string, debitAccountID, creditAccountID uint64) models.SSOTJournalEntry {
		t.Helper()
		entry := models.SSOTJournalEntry{
			EntryNumber:     entryNumber,
			SourceType:      sourceType,
			EntryDate:       time.Date(2026, 5, 1, 0, 0, 0, 0, time.UTC),
			Description:     "Test journal " + entryNumber,
			Reference:       entryNumber,
			TotalDebit:      decimal.NewFromInt(1000),
			TotalCredit:     decimal.NewFromInt(1000),
			Status:          models.SSOTStatusPosted,
			IsBalanced:      true,
			IsAutoGenerated: true,
			CreatedBy:       1,
		}
		if err := db.Create(&entry).Error; err != nil {
			t.Fatalf("create journal %s: %v", entryNumber, err)
		}
		lines := []models.SSOTJournalLine{
			{
				JournalID:    entry.ID,
				AccountID:    debitAccountID,
				LineNumber:   1,
				Description:  "Debit line",
				DebitAmount:  decimal.NewFromInt(1000),
				CreditAmount: decimal.Zero,
			},
			{
				JournalID:    entry.ID,
				AccountID:    creditAccountID,
				LineNumber:   2,
				Description:  "Credit line",
				DebitAmount:  decimal.Zero,
				CreditAmount: decimal.NewFromInt(1000),
			},
		}
		if err := db.Create(&lines).Error; err != nil {
			t.Fatalf("create journal lines %s: %v", entryNumber, err)
		}
		return entry
	}

	needsAdjustment := createJournal("JE-NEEDS-ADJ", models.SSOTSourceTypeSale, 10, 11)
	alreadyAdjusted := createJournal("JE-ALREADY-ADJ", models.SSOTSourceTypeSale, 10, 11)
	notRequired := createJournal("JE-NOT-REQUIRED", models.SSOTSourceTypePayment, 12, 13)

	adjustedID := alreadyAdjusted.ID
	adjustmentEntry := models.SSOTJournalEntry{
		EntryNumber:             "JE-ADJ",
		SourceType:              models.SSOTSourceTypeAdjustment,
		EntryDate:               time.Date(2026, 5, 2, 0, 0, 0, 0, time.UTC),
		Description:             "Adjustment for already adjusted journal",
		Reference:               "ADJ-JE-ALREADY-ADJ",
		TotalDebit:              decimal.NewFromInt(100),
		TotalCredit:             decimal.NewFromInt(100),
		Status:                  models.SSOTStatusDraft,
		IsBalanced:              true,
		IsAutoGenerated:         false,
		AdjustmentOf:            &adjustedID,
		AdjustmentCategoryCode:  models.JournalAdjustmentCategorySalesRevenueRecognition,
		AdjustmentCategoryLabel: "Pengakuan Pendapatan Sales",
		CreatedBy:               1,
	}
	if err := db.Create(&adjustmentEntry).Error; err != nil {
		t.Fatalf("create related adjustment: %v", err)
	}

	service := NewUnifiedJournalService(db)

	needsResponse, err := service.GetJournalEntries(JournalFilters{
		AdjustmentRequirement: "NEEDS_ADJUSTMENT",
		Limit:                 100,
	})
	if err != nil {
		t.Fatalf("filter needs adjustment: %v", err)
	}
	if len(needsResponse.Data) != 1 || needsResponse.Data[0].ID != needsAdjustment.ID {
		t.Fatalf("expected only %s in needs adjustment filter, got %#v", needsAdjustment.EntryNumber, needsResponse.Data)
	}
	if !needsResponse.Data[0].AdjustmentRequired || needsResponse.Data[0].AdjustmentCompleted {
		t.Fatalf("expected needs-adjustment flag without completed flag, got required=%v completed=%v", needsResponse.Data[0].AdjustmentRequired, needsResponse.Data[0].AdjustmentCompleted)
	}

	adjustedResponse, err := service.GetJournalEntries(JournalFilters{
		AdjustmentRequirement: "ADJUSTED",
		Limit:                 100,
	})
	if err != nil {
		t.Fatalf("filter adjusted: %v", err)
	}
	if len(adjustedResponse.Data) != 1 || adjustedResponse.Data[0].ID != alreadyAdjusted.ID {
		t.Fatalf("expected only %s in adjusted filter, got %#v", alreadyAdjusted.EntryNumber, adjustedResponse.Data)
	}
	if !adjustedResponse.Data[0].AdjustmentRequired || !adjustedResponse.Data[0].AdjustmentCompleted {
		t.Fatalf("expected adjusted flags, got required=%v completed=%v", adjustedResponse.Data[0].AdjustmentRequired, adjustedResponse.Data[0].AdjustmentCompleted)
	}

	notRequiredResponse, err := service.GetJournalEntries(JournalFilters{
		AdjustmentRequirement: "NOT_REQUIRED",
		Limit:                 100,
	})
	if err != nil {
		t.Fatalf("filter not required: %v", err)
	}
	if len(notRequiredResponse.Data) != 1 {
		t.Fatalf("expected only non-eligible posted source as not required, got %#v", notRequiredResponse.Data)
	}
	seenNotRequired := false
	for _, entry := range notRequiredResponse.Data {
		if entry.ID == notRequired.ID {
			seenNotRequired = true
		}
		if entry.ID == needsAdjustment.ID || entry.ID == alreadyAdjusted.ID {
			t.Fatalf("required entry leaked into not-required filter: %#v", entry)
		}
	}
	if !seenNotRequired {
		t.Fatalf("expected %s in not-required filter, got %#v", notRequired.EntryNumber, notRequiredResponse.Data)
	}
}
