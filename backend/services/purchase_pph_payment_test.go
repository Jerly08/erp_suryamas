func TestPayPurchasePPhCreatesSettlementJournalsAcrossDifferentDates(t *testing.T) {
	db, userID, suffix := newPurchasePPhPaymentE2ETestDB(t)

	expense := createSSOTTestAccount(t, db, "8E2E"+suffix, "BEBAN TEST PPH "+suffix, models.AccountTypeExpense, models.CategoryOperatingExpense)
	cashBankGL := createSSOTTestAccount(t, db, "1E2E"+suffix, "BANK TEST PPH "+suffix, models.AccountTypeAsset, models.CategoryCurrentAsset)
	payable := createSSOTTestAccount(t, db, "2E2E"+suffix, "UTANG USAHA TEST PPH "+suffix, models.AccountTypeLiability, models.CategoryCurrentLiability)
	pph23Payable, err := NewTaxAccountHelper(db).GetPurchaseWithholdingTax23PayableAccount(db)
	require.NoError(t, err)

	cashBank := models.CashBank{
		Code:             "CB" + suffix,
		Name:             "BANK TEST PPH " + suffix,
		Type:             models.CashBankTypeBank,
		AccountID:        cashBankGL.ID,
		Currency:         "IDR",
		Balance:          1000000,
		BookBalanceIDR:   1000000,
		LastExchangeRate: 1,
		IsActive:         true,
	}
	require.NoError(t, db.Create(&cashBank).Error)
	require.NoError(t, db.Create(&models.CashBankTransaction{
		CashBankID:      cashBank.ID,
		ReferenceType:   "OPENING_BALANCE",
		Amount:          1000000,
		Currency:        "IDR",
		ExchangeRate:    1,
		BookAmountIDR:   1000000,
		BalanceAfter:    1000000,
		TransactionDate: time.Date(2026, time.June, 1, 0, 0, 0, 0, time.UTC),
		Notes:           "Opening balance for PPh payment test",
	}).Error)
	require.NoError(t, NewCashBankCurrencyGuard(db).EnforceAfterTransaction(db, cashBank.ID))
	var readyCashBank models.CashBank
	require.NoError(t, db.First(&readyCashBank, cashBank.ID).Error)
	require.InDelta(t, 1000000, readyCashBank.AvailableBalance(), 0.01)

	vendor := models.Contact{Code: "V" + suffix, Name: "Vendor PPh Test " + suffix, Type: models.ContactTypeVendor, IsActive: true}
	require.NoError(t, db.Create(&vendor).Error)
	product := models.Product{Code: "P" + suffix, Name: "Jasa PPh Test " + suffix, Unit: "pcs", IsService: true, IsActive: true}
	require.NoError(t, db.Create(&product).Error)

	purchaseDate := time.Date(2026, time.June, 5, 0, 0, 0, 0, time.UTC)
	purchase := models.Purchase{
		Code:                  "POE2E" + suffix,
		VendorID:              vendor.ID,
		UserID:                userID,
		Date:                  purchaseDate,
		DueDate:               purchaseDate,
		NetBeforeTax:          12090909.09,
		PPh23Amount:           241818.18,
		TotalTaxDeductions:    241818.18,
		TotalAmount:           11849090.91,
		OutstandingAmount:     11849090.91,
		PaymentMethod:         models.PurchasePaymentCredit,
		CreditAccountID:       &payable.ID,
		Status:                models.PurchaseStatusApproved,
		ApprovalStatus:        "APPROVED",
		PPhPaymentStatus:      models.PurchasePPhPaymentStatusUnpaid,
		ApprovalAmountBasis:   "SUBTOTAL_BEFORE_DISCOUNT",
		InvoiceMatchingStatus: "NOT_APPLICABLE",
	}
	require.NoError(t, db.Create(&purchase).Error)

	productID := product.ID
	require.NoError(t, db.Create(&models.PurchaseItem{
		PurchaseID:       purchase.ID,
		ProductID:        &productID,
		Quantity:         1,
		UnitPrice:        12090909.09,
		TotalPrice:       12090909.09,
		ExpenseAccountID: expense.ID,
	}).Error)

	sourceID := uint64(purchase.ID)
	initialJournal := models.SSOTJournalEntry{
		SourceType:      models.SSOTSourceTypePurchase,
		SourceID:        &sourceID,
		SourceCode:      purchase.Code,
		EntryDate:       purchaseDate,
		Description:     "Purchase journal with PPh payable",
		Reference:       purchase.Code,
		TotalDebit:      decimal.RequireFromString("12090909.09"),
		TotalCredit:     decimal.RequireFromString("12090909.09"),
		Status:          models.SSOTStatusPosted,
		IsBalanced:      true,
		IsAutoGenerated: true,
		CreatedBy:       uint64(userID),
	}
	require.NoError(t, db.Create(&initialJournal).Error)
	require.NoError(t, db.Create(&[]models.SSOTJournalLine{
		{
			JournalID:    initialJournal.ID,
			AccountID:    uint64(expense.ID),
			LineNumber:   1,
			Description:  "Purchase expense/inventory",
			DebitAmount:  decimal.RequireFromString("12090909.09"),
			CreditAmount: decimal.Zero,
		},
		{
			JournalID:    initialJournal.ID,
			AccountID:    uint64(pph23Payable.ID),
			LineNumber:   2,
			Description:  "Utang PPh 23",
			DebitAmount:  decimal.Zero,
			CreditAmount: decimal.RequireFromString("241818.18"),
		},
		{
			JournalID:    initialJournal.ID,
			AccountID:    uint64(payable.ID),
			LineNumber:   3,
			Description:  "Vendor payable remainder",
			DebitAmount:  decimal.Zero,
			CreditAmount: decimal.RequireFromString("11849090.91"),
		},
	}).Error)

	service := &PurchaseService{db: db}

	firstPayment, err := service.PayPurchasePPh(purchase.ID, models.PurchasePPhPaymentRequest{
		PaymentDate: "2026-06-10",
		Amount:      100000,
		CashBankID:  cashBank.ID,
		Reference:   "SSP-PPH-PARTIAL",
		Notes:       "Bayar sebagian PPh 23",
	}, userID)
	require.NoError(t, err)
	require.Equal(t, models.PurchasePPhPaymentStatusPartialPaid, firstPayment.PPhPaymentStatus)
	require.InDelta(t, 100000, firstPayment.PPhPaidAmount, 0.01)

	finalPayment, err := service.PayPurchasePPh(purchase.ID, models.PurchasePPhPaymentRequest{
		PaymentDate: "2026-06-20",
		Amount:      141818.18,
		CashBankID:  cashBank.ID,
		Reference:   "SSP-PPH-FINAL",
		Notes:       "Pelunasan PPh 23 di tanggal berbeda",
	}, userID)
	require.NoError(t, err)
	require.Equal(t, models.PurchasePPhPaymentStatusPaid, finalPayment.PPhPaymentStatus)
	require.InDelta(t, 241818.18, finalPayment.PPhPaidAmount, 0.01)
	require.NotNil(t, finalPayment.PPhPaymentDate)
	require.Equal(t, "2026-06-20", finalPayment.PPhPaymentDate.Format("2006-01-02"))

	var paymentJournals []models.SSOTJournalEntry
	require.NoError(t, db.
		Preload("Lines").
		Where("source_type = ? AND source_id = ?", models.SSOTSourceTypePurchasePPhPayment, sourceID).
		Order("entry_date ASC").
		Find(&paymentJournals).Error)
	require.Len(t, paymentJournals, 2)

	assertPPhSettlementJournal := func(entry models.SSOTJournalEntry, expectedDate string, expectedAmount string) {
		require.Equal(t, expectedDate, entry.EntryDate.Format("2006-01-02"))
		require.Equal(t, models.SSOTStatusPosted, entry.Status)
		require.Equal(t, expectedAmount, entry.TotalDebit.Round(2).StringFixed(2))
		require.Equal(t, expectedAmount, entry.TotalCredit.Round(2).StringFixed(2))

		var pphDebit, bankCredit decimal.Decimal
		for _, line := range entry.Lines {
			switch line.AccountID {
			case uint64(pph23Payable.ID):
				pphDebit = pphDebit.Add(line.DebitAmount)
			case uint64(cashBankGL.ID):
				bankCredit = bankCredit.Add(line.CreditAmount)
			}
		}
		require.Equal(t, expectedAmount, pphDebit.Round(2).StringFixed(2))
		require.Equal(t, expectedAmount, bankCredit.Round(2).StringFixed(2))
	}
	assertPPhSettlementJournal(paymentJournals[0], "2026-06-10", "100000.00")
	assertPPhSettlementJournal(paymentJournals[1], "2026-06-20", "141818.18")

	var reloadedCashBank models.CashBank
	require.NoError(t, db.First(&reloadedCashBank, cashBank.ID).Error)
	require.InDelta(t, 758181.82, reloadedCashBank.Balance, 0.01)
	require.InDelta(t, 758181.82, reloadedCashBank.BookBalanceIDR, 0.01)

	var cashTransactions []models.CashBankTransaction
	require.NoError(t, db.
		Where("cash_bank_id = ? AND reference_type = ?", cashBank.ID, models.SSOTSourceTypePurchasePPhPayment).
		Order("transaction_date ASC").
		Find(&cashTransactions).Error)
	require.Len(t, cashTransactions, 2)
	require.Equal(t, "2026-06-10", cashTransactions[0].TransactionDate.Format("2006-01-02"))
	require.InDelta(t, -100000, cashTransactions[0].Amount, 0.01)
	require.Equal(t, "2026-06-20", cashTransactions[1].TransactionDate.Format("2006-01-02"))
	require.InDelta(t, -141818.18, cashTransactions[1].Amount, 0.01)

	adapter := NewPurchaseSSOTJournalAdapter(db, NewUnifiedJournalService(db), nil, nil)
	relatedEntries, err := adapter.GetPurchaseRelatedJournalEntries(context.Background(), sourceID, true)
	require.NoError(t, err)

	foundPPhSettlementEntries := 0
	for _, entry := range relatedEntries {
		if entry.SourceType == models.SSOTSourceTypePurchasePPhPayment {
			foundPPhSettlementEntries++
		}
	}
	require.Equal(t, 2, foundPPhSettlementEntries)
}

func newPurchasePPhPaymentE2ETestDB(t *testing.T) (*gorm.DB, uint, string) {
	t.Helper()

	suffix := time.Now().Format("150405")
	if testDBURL := strings.TrimSpace(os.Getenv("TEST_DATABASE_URL")); testDBURL != "" {
		rootDB, err := gorm.Open(postgres.Open(testDBURL), &gorm.Config{})
		require.NoError(t, err)

		sqlDB, err := rootDB.DB()
		require.NoError(t, err)

		tx := rootDB.Begin()
		require.NoError(t, tx.Error)
		t.Cleanup(func() {
			_ = tx.Rollback().Error
			_ = sqlDB.Close()
		})

		var user models.User
		require.NoError(t, tx.
			Where("username = ? OR email = ?", "admin", "admin@company.com").
			First(&user).Error)

		return tx, user.ID, suffix
	}

	db := newPurchaseJournalSSOTTestDB(t)
	require.NoError(t, db.AutoMigrate(
		&models.Contact{},
		&models.Product{},
		&models.Purchase{},
		&models.PurchaseItem{},
		&models.CashBankTransaction{},
		&models.AccountingPeriod{},
		&models.TaxConfig{},
	))
	return db, 1, suffix
}
