package services

import (
	"testing"
	"time"

	"app-sistem-akuntansi/models"
	"github.com/glebarez/sqlite"
	"github.com/shopspring/decimal"
	"gorm.io/gorm"
)

func TestGetJournalEntriesPrioritizesDraftAdjustments(t *testing.T) {
	db, err := gorm.Open(sqlite.Open("file:"+t.Name()+"?mode=memory&cache=shared"), &gorm.Config{})
	if err != nil {
		t.Fatalf("open sqlite db: %v", err)
	}

	if err := db.AutoMigrate(&models.User{}, &models.SSOTJournalEntry{}, &models.SSOTJournalLine{}); err != nil {
		t.Fatalf("auto migrate: %v", err)
	}

	user := models.User{
		Username: "journal_order_test",
		Email:    "journal-order@test.local",
		Password: "hashed",
		Role:     models.RoleFinanceStaff,
		IsActive: true,
	}
	if err := db.Create(&user).Error; err != nil {
		t.Fatalf("create user: %v", err)
	}

	makeEntry := func(entryNumber, sourceType, status string, entryDate, createdAt time.Time) models.SSOTJournalEntry {
		return models.SSOTJournalEntry{
			EntryNumber:     entryNumber,
			SourceType:      sourceType,
			EntryDate:       entryDate,
			Description:     entryNumber,
			Reference:       entryNumber,
			TotalDebit:      decimal.NewFromInt(1000),
			TotalCredit:     decimal.NewFromInt(1000),
			Status:          status,
			IsBalanced:      true,
			IsAutoGenerated: false,
			CreatedBy:       uint64(user.ID),
			CreatedAt:       createdAt,
			UpdatedAt:       createdAt,
		}
	}

	olderPosted := makeEntry(
		"JE-OLDER",
		models.SSOTSourceTypeManual,
		models.SSOTStatusPosted,
		time.Date(2026, 1, 5, 0, 0, 0, 0, time.UTC),
		time.Date(2026, 1, 5, 10, 0, 0, 0, time.UTC),
	)
	if err := db.Create(&olderPosted).Error; err != nil {
		t.Fatalf("create older posted entry: %v", err)
	}

	newerPosted := makeEntry(
		"JE-NEWER",
		models.SSOTSourceTypeManual,
		models.SSOTStatusPosted,
		time.Date(2026, 4, 20, 0, 0, 0, 0, time.UTC),
		time.Date(2026, 4, 20, 9, 0, 0, 0, time.UTC),
	)
	if err := db.Create(&newerPosted).Error; err != nil {
		t.Fatalf("create newer posted entry: %v", err)
	}

	adjustmentOf := olderPosted.ID
	draftAdjustment := makeEntry(
		"JE-DRAFT-ADJ",
		models.SSOTSourceTypeAdjustment,
		models.SSOTStatusDraft,
		time.Date(2026, 1, 5, 0, 0, 0, 0, time.UTC),
		time.Date(2026, 4, 21, 15, 0, 0, 0, time.UTC),
	)
	draftAdjustment.AdjustmentOf = &adjustmentOf
	if err := db.Create(&draftAdjustment).Error; err != nil {
		t.Fatalf("create draft adjustment entry: %v", err)
	}

	service := NewUnifiedJournalService(db)
	resp, err := service.GetJournalEntries(JournalFilters{
		Page:  1,
		Limit: 10,
	})
	if err != nil {
		t.Fatalf("get journal entries: %v", err)
	}

	if len(resp.Data) != 3 {
		t.Fatalf("expected 3 entries, got %d", len(resp.Data))
	}

	if resp.Data[0].ID != draftAdjustment.ID {
		t.Fatalf("expected draft adjustment to be listed first, got entry id %d", resp.Data[0].ID)
	}
}
