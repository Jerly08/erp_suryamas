// GetJournalEntries returns paginated journal entries based on simple filters
func (s *UnifiedJournalService) GetJournalEntries(filters interface{}) (*JournalResponse, error) {
	f, ok := filters.(JournalFilters)
	if !ok {
		return nil, fmt.Errorf("invalid filters type")
	}

	query := s.db.Model(&models.SSOTJournalEntry{}).Where("status = ?", models.SSOTStatusPosted).Where("deleted_at IS NULL")
	if f.SourceType != "" {
		query = query.Where("source_type = ?", f.SourceType)
	}
	if f.SourceID != nil {
		query = query.Where("source_id = ?", *f.SourceID)
	}
	if f.DateFrom != nil {
		query = query.Where("entry_date >= ?", *f.DateFrom)
	}
	if f.DateTo != nil {
		query = query.Where("entry_date < ?", *f.DateTo)
	}

	var total int64
	if err := query.Count(&total).Error; err != nil {
		return nil, fmt.Errorf("failed to count journal entries: %w", err)
	}

	page := f.Page
	if page <= 0 {
		page = 1
	}
	limit := f.Limit
	if limit <= 0 {
		limit = 20
	}
	offset := (page - 1) * limit

	var entries []models.SSOTJournalEntry
	if err := query.
		Preload("Lines").
		Preload("Lines.Account").
		Preload("Creator").
		Order("entry_date DESC, id DESC").
		Limit(limit).
		Offset(offset).
		Find(&entries).Error; err != nil {
		return nil, fmt.Errorf("failed to query journal entries: %w", err)
	}

	return &JournalResponse{
		Data:       entries,
		Total:      total,
		Page:       page,
		Limit:      limit,
		TotalPages: int((total + int64(limit) - 1) / int64(limit)),
	}, nil
}

// UpdateJournalEntry updates an existing journal entry
func (s *UnifiedJournalService) UpdateJournalEntry(id uint64, req *JournalEntryRequest) (*models.SSOTJournalEntry, error) {
	var entry models.SSOTJournalEntry
	if err := s.db.First(&entry, id).Error; err != nil {
		return nil, fmt.Errorf("journal entry not found")
	}

	if entry.Status != models.SSOTStatusDraft {
		return nil, fmt.Errorf("only draft entries can be updated")
	}

	// Validate lines
	if len(req.Lines) < 2 {
		return nil, fmt.Errorf("at least two journal lines are required")
	}

	var totalDebit, totalCredit decimal.Decimal
	for _, l := range req.Lines {
		totalDebit = totalDebit.Add(l.DebitAmount)
		totalCredit = totalCredit.Add(l.CreditAmount)
	}

	if !totalDebit.Equal(totalCredit) {
		return nil, fmt.Errorf("journal entry is not balanced")
	}

	return &entry, s.db.Transaction(func(tx *gorm.DB) error {
		// Update header
		entry.EntryDate = req.EntryDate
		entry.Description = req.Description
		entry.Reference = req.Reference
		entry.TotalDebit = totalDebit
		entry.TotalCredit = totalCredit
		// Don't change CreatedBy, but maybe UpdatedAt is handled by GORM

		if err := tx.Save(&entry).Error; err != nil {
			return err
		}

		// Replace lines: Delete old ones
		if err := tx.Where("journal_id = ?", entry.ID).Delete(&models.SSOTJournalLine{}).Error; err != nil {
			return err
		}

		// Create new lines
		for i, l := range req.Lines {
			line := &models.SSOTJournalLine{
				JournalID:    entry.ID,
				AccountID:    l.AccountID,
				LineNumber:   i + 1,
				Description:  l.Description,
				DebitAmount:  l.DebitAmount,
				CreditAmount: l.CreditAmount,
			}
			if err := tx.Create(line).Error; err != nil {
				return err
			}
		}
		return nil
	})
}

