// UnifiedJournalService STUB - prevents auto-posting
type UnifiedJournalService struct {
	db *gorm.DB
}

func NewUnifiedJournalService(db *gorm.DB) *UnifiedJournalService {
	return &UnifiedJournalService{db: db}
}

func normalizeJournalMetadata(sourceType string, sourceID uint64, adjustmentOf *uint64) (string, *uint64, bool) {
	normalizedSourceType := strings.ToUpper(strings.TrimSpace(sourceType))
	if normalizedSourceType == "" {
		normalizedSourceType = models.SSOTSourceTypeManual
	}

	var sourceIDPtr *uint64
	if sourceID > 0 {
		sourceIDCopy := sourceID
		sourceIDPtr = &sourceIDCopy
	}

	isAutoGenerated := !requiresManualJournalApproval(normalizedSourceType, adjustmentOf)
	return normalizedSourceType, sourceIDPtr, isAutoGenerated
}

func normalizeOptionalUint64(value *uint64) *uint64 {
	if value == nil || *value == 0 {
		return nil
	}

	valueCopy := *value
	return &valueCopy
}

func requiresManualJournalApproval(sourceType string, adjustmentOf *uint64) bool {
	switch strings.ToUpper(strings.TrimSpace(sourceType)) {
	case models.SSOTSourceTypeManual:
		return true
	case models.SSOTSourceTypeAdjustment:
		return normalizeOptionalUint64(adjustmentOf) != nil
	default:
		return false
	}
}

func creatorBypassesManualJournalApproval(req *JournalEntryRequest) bool {
	return req != nil && (req.SystemGenerated || (req.RequestedByFinanceManager && !req.RequireDirectorApproval))
}

func shouldForceManualJournalDraft(req *JournalEntryRequest, sourceType string, adjustmentOf *uint64) bool {
	return requiresManualJournalApproval(sourceType, adjustmentOf) && !creatorBypassesManualJournalApproval(req)
}

func isJournalDirectorApprovalPending(entry *models.SSOTJournalEntry) bool {
	if entry == nil {
		return false
	}

	return entry.Status == models.SSOTStatusDraft &&
		entry.RequireDirectorApproval &&
		strings.EqualFold(strings.TrimSpace(entry.ApprovalStage), models.SSOTApprovalStageDirector)
}

func shouldDisallowCashBankLinkedAccounts(sourceType string, adjustmentOf *uint64, systemGenerated bool) bool {
	// Manual journals must not directly post to a cash/bank-linked COA. A
	// server-generated, approved correction is the only narrow exception.
	return requiresManualJournalApproval(sourceType, adjustmentOf) && !systemGenerated
}

func journalAccountingDateStart(date time.Time) time.Time {
	if date.IsZero() {
		return date
	}
	localDate := date.In(utils.JakartaTZ)
	return time.Date(localDate.Year(), localDate.Month(), localDate.Day(), 0, 0, 0, 0, utils.JakartaTZ)
}

func validateAdjustmentReference(tx *gorm.DB, sourceType string, adjustmentOf *uint64, entryDate time.Time) (*uint64, error) {
	normalizedAdjustmentOf := normalizeOptionalUint64(adjustmentOf)
	if normalizedAdjustmentOf == nil {
		return nil, nil
	}

	if strings.ToUpper(strings.TrimSpace(sourceType)) != models.SSOTSourceTypeAdjustment {
		return nil, fmt.Errorf("adjustment_of hanya boleh dipakai untuk jurnal adjustment")
	}

	var original models.SSOTJournalEntry
	if err := tx.Where("id = ? AND deleted_at IS NULL", *normalizedAdjustmentOf).First(&original).Error; err != nil {
		if err == gorm.ErrRecordNotFound {
			return nil, fmt.Errorf("jurnal asal adjustment tidak ditemukan")
		}
		return nil, fmt.Errorf("failed to load jurnal asal adjustment: %w", err)
	}

	if original.SourceType == models.SSOTSourceTypeAdjustment {
		return nil, fmt.Errorf("jurnal adjustment tidak bisa menjadi jurnal asal adjustment baru")
	}

	if original.SourceType == models.SSOTSourceTypeReversal {
		return nil, fmt.Errorf("jurnal reversal tidak bisa menjadi jurnal asal adjustment")
	}

	if original.Status != models.SSOTStatusPosted {
		return nil, fmt.Errorf("jurnal asal adjustment harus berstatus POSTED")
	}

	if journalAccountingDateStart(entryDate).Before(journalAccountingDateStart(original.EntryDate)) {
		return nil, fmt.Errorf("tanggal adjustment tidak boleh lebih awal dari jurnal asal")
	}

	return normalizedAdjustmentOf, nil
}

func findPostedSourceJournalIDForAdjustment(tx *gorm.DB, sourceType string, sourceID uint64, adjustmentDate time.Time) *uint64 {
	if tx == nil || strings.TrimSpace(sourceType) == "" || sourceID == 0 {
		return nil
	}

	var original models.SSOTJournalEntry
	query := tx.
		Where("source_type = ? AND source_id = ? AND status = ? AND deleted_at IS NULL",
			strings.ToUpper(strings.TrimSpace(sourceType)), sourceID, models.SSOTStatusPosted)
	if !adjustmentDate.IsZero() {
		query = query.Where("entry_date <= ?", adjustmentDate)
	}

	if err := query.Order("entry_date ASC, id ASC").First(&original).Error; err != nil {
		return nil
	}

	originalID := original.ID
	return &originalID
}

func resolveJournalAdjustmentCategory(sourceType string, adjustmentOf *uint64, requestedCode string) (string, string, error) {
	normalizedSourceType := strings.ToUpper(strings.TrimSpace(sourceType))
	normalizedCode := models.NormalizeJournalAdjustmentCategoryCode(requestedCode)
	isManualAdjustmentOfPostedJournal := normalizedSourceType == models.SSOTSourceTypeAdjustment &&
		adjustmentOf != nil &&
		*adjustmentOf != 0

	if normalizedCode == "" {
		if isManualAdjustmentOfPostedJournal {
			return "", "", fmt.Errorf("kategori transaksi adjustment wajib dipilih")
		}
		return "", "", nil
	}

	category, exists := models.GetJournalAdjustmentCategory(normalizedCode)
	if !exists {
		return "", "", fmt.Errorf("kategori transaksi adjustment tidak valid: %s", requestedCode)
	}

	return category.Code, category.Label, nil
}

func validatePersistedJournalAdjustmentCategory(entry *models.SSOTJournalEntry) error {
	if entry == nil {
		return nil
	}
	_, _, err := resolveJournalAdjustmentCategory(entry.SourceType, entry.AdjustmentOf, entry.AdjustmentCategoryCode)
	return err
}

func journalHasRelatedAdjustment(entry *models.SSOTJournalEntry) bool {
	if entry == nil {
		return false
	}
	for _, adjustment := range entry.AdjustmentEntries {
		if adjustment.DeletedAt == nil && adjustment.Status != models.SSOTStatusCancelled {
			return true
		}
	}
	return false
}

func journalAdjustmentText(entry *models.SSOTJournalEntry) string {
	if entry == nil {
		return ""
	}
	parts := []string{
		entry.SourceType,
		entry.SourceCode,
		entry.Reference,
		entry.Description,
		entry.Notes,
	}
	for _, line := range entry.Lines {
		parts = append(parts, line.Description)
		if line.Account != nil {
			parts = append(parts, line.Account.Code, line.Account.Name)
		}
	}
	return strings.ToUpper(strings.Join(parts, " "))
}

func inferJournalAdjustmentRequirement(entry *models.SSOTJournalEntry) (models.JournalAdjustmentCategoryDefinition, string, bool) {
	if entry == nil {
		return models.JournalAdjustmentCategoryDefinition{}, "", false
	}

	sourceType := strings.ToUpper(strings.TrimSpace(entry.SourceType))
	if sourceType == models.SSOTSourceTypeAdjustment || sourceType == models.SSOTSourceTypeReversal {
		return models.JournalAdjustmentCategoryDefinition{}, "", false
	}
	if entry.Status != models.SSOTStatusPosted || entry.ReversedBy != nil {
		return models.JournalAdjustmentCategoryDefinition{}, "", false
	}

	text := journalAdjustmentText(entry)
	hasAny := func(values ...string) bool {
		for _, value := range values {
			if strings.Contains(text, strings.ToUpper(value)) {
				return true
			}
		}
		return false
	}

	if strings.HasPrefix(sourceType, "PAYROLL") || hasAny("PPH 21", "PPH21", "PPH PAYROLL") {
		category, _ := models.GetJournalAdjustmentCategory(models.JournalAdjustmentCategoryPPh21Accrual)
		return category, "Terindikasi ada pembebanan PPh 21/accrual pajak payroll.", true
	}
	if hasAny("PPH 23", "PPH23") {
		category, _ := models.GetJournalAdjustmentCategory(models.JournalAdjustmentCategoryPPh23Accrual)
		return category, "Terindikasi ada pembebanan PPh 23 atau PPh 23 menyusul.", true
	}
	if sourceType == models.SSOTSourceTypeSale && hasAny("PIUTANG USAHA", "1102") {
		category, _ := models.GetJournalAdjustmentCategory(models.JournalAdjustmentCategorySalesRevenueRecognition)
		return category, "Sales diakui ke Piutang Usaha sebelum kas diterima.", true
	}
	if hasAny("ACCRUED COGS", "ACCRUED HPP", "RELEASE ACCRUED", "ESTIMATED HPP BACKORDER", "BACKORDER", salesBackorderClearingAccountCode) {
		category, _ := models.GetJournalAdjustmentCategory(models.JournalAdjustmentCategoryCOGSHPPRecognition)
		return category, "Terindikasi COGS/HPP terkait accrued, release, atau backorder.", true
	}
	if sourceType == models.SSOTSourceTypePrepaidAmortization ||
		sourceType == models.SSOTSourceTypePrepaidTermination ||
		hasAny("PREPAID", "AMORTISASI", "AMORTIZATION") {
		category, _ := models.GetJournalAdjustmentCategory(models.JournalAdjustmentCategoryPrepaidMonthlyRealization)
		return category, "Terindikasi realisasi prepaid bulanan.", true
	}

	return models.JournalAdjustmentCategoryDefinition{}, "", false
}

const journalSettlementTolerance = 0.005

func journalAmountIsSettled(total, paid float64) bool {
	return total <= journalSettlementTolerance || paid+journalSettlementTolerance >= total
}

// journalBusinessTransactionResolved prevents the adjustment mapping from
// becoming a permanent label. A mapped journal only needs follow-up while its
// underlying business transaction is still open.
func journalBusinessTransactionResolved(db *gorm.DB, entry *models.SSOTJournalEntry, categoryCode string) bool {
	if db == nil || entry == nil || entry.SourceID == nil || *entry.SourceID == 0 {
		return false
	}

	sourceType := strings.ToUpper(strings.TrimSpace(entry.SourceType))
	sourceID := *entry.SourceID

	if strings.HasPrefix(sourceType, "PAYROLL") {
		var run models.PayrollRun
		if err := db.First(&run, uint(sourceID)).Error; err != nil {
			return false
		}

		return journalAmountIsSettled(run.TotalOverall, run.SalaryPaidAmount) &&
			journalAmountIsSettled(run.TotalBPJS, run.BPJSPaidAmount) &&
			journalAmountIsSettled(run.TotalPPh, run.PPhPaidAmount)
	}

	switch categoryCode {
	case models.JournalAdjustmentCategoryPPh23Accrual:
		if sourceType != models.SSOTSourceTypeSale {
			return false
		}
		var sale models.Sale
		if err := db.First(&sale, uint(sourceID)).Error; err != nil {
			return false
		}
		return sale.PPh23Amount <= journalSettlementTolerance || sale.PPh23SettlementJournalEntryID != nil

	case models.JournalAdjustmentCategorySalesRevenueRecognition:
		if sourceType != models.SSOTSourceTypeSale {
			return false
		}
		var sale models.Sale
		if err := db.First(&sale, uint(sourceID)).Error; err != nil {
			return false
		}
		return sale.OutstandingAmount <= journalSettlementTolerance

	case models.JournalAdjustmentCategoryCOGSHPPRecognition:
		if sourceType != models.SSOTSourceTypeSale {
			return false
		}
		var openBackorders int64
		if err := db.Model(&models.SaleItem{}).
			Where("sale_id = ? AND backorder_quantity > 0 AND deleted_at IS NULL", uint(sourceID)).
			Count(&openBackorders).Error; err != nil {
			return false
		}
		return openBackorders == 0

	case models.JournalAdjustmentCategoryPrepaidMonthlyRealization:
		switch sourceType {
		case models.SSOTSourceTypePrepaidAmortization:
			var schedule models.PrepaidSchedule
			if err := db.First(&schedule, uint(sourceID)).Error; err != nil {
				return false
			}
			status := strings.ToUpper(strings.TrimSpace(schedule.Status))
			return status == "POSTED" || status == "CANCELLED"
		case models.SSOTSourceTypePrepaidTermination:
			var prepaid models.PrepaidExpense
			if err := db.First(&prepaid, uint(sourceID)).Error; err != nil {
				return false
			}
			status := strings.ToUpper(strings.TrimSpace(prepaid.Status))
			return status == "COMPLETED" || status == "TERMINATED"
		}
	}

	return false
}

func clearJournalAdjustmentRequirement(entry *models.SSOTJournalEntry) {
	entry.AdjustmentRequired = false
	entry.AdjustmentRequirementCode = ""
	entry.AdjustmentRequirementLabel = ""
	entry.AdjustmentRequirementCOA = ""
	entry.AdjustmentRequirementReason = ""
	entry.AdjustmentRequirementTagline = ""
}

func hydrateJournalAdjustmentRequirement(db *gorm.DB, entry *models.SSOTJournalEntry) {
	if entry == nil {
		return
	}

	entry.AdjustmentCompleted = journalHasRelatedAdjustment(entry)

	category, reason, required := inferJournalAdjustmentRequirement(entry)
	if !required {
		clearJournalAdjustmentRequirement(entry)
		return
	}

	if !entry.AdjustmentCompleted && journalBusinessTransactionResolved(db, entry, category.Code) {
		clearJournalAdjustmentRequirement(entry)
		return
	}

	entry.AdjustmentRequired = true
	entry.AdjustmentRequirementCode = category.Code
	entry.AdjustmentRequirementLabel = category.Label
	entry.AdjustmentRequirementCOA = category.COA
	entry.AdjustmentRequirementReason = reason
	entry.AdjustmentRequirementTagline = models.JournalAdjustmentRequirementTagline
}

func hydrateJournalAdjustmentRequirements(db *gorm.DB, entries []models.SSOTJournalEntry) {
	for idx := range entries {
		hydrateJournalAdjustmentRequirement(db, &entries[idx])
	}
}

