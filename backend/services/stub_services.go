// UpdateJournalEntry updates an existing journal entry
func (s *UnifiedJournalService) UpdateJournalEntry(id uint64, req *JournalEntryRequest) (*models.SSOTJournalEntry, error) {
	var entry models.SSOTJournalEntry
	if err := s.db.First(&entry, id).Error; err != nil {
		return nil, fmt.Errorf("journal entry not found")
	}

	if entry.Status != models.SSOTStatusDraft {
		return nil, fmt.Errorf("only draft entries can be updated")
	}
	if isJournalDirectorApprovalPending(&entry) {
		return nil, fmt.Errorf("journal draft yang sudah dikirim ke director tidak bisa diubah")
	}

	// Guard: check if journal entry date is in a closed accounting period
	if err := CheckClosedPeriod(s.db, entry.EntryDate); err != nil {
		return nil, err
	}

	effectiveSourceType := strings.TrimSpace(entry.SourceType)
	if effectiveSourceType == "" {
		effectiveSourceType = models.SSOTSourceTypeManual
	}
	adjustmentOf, err := validateAdjustmentReference(s.db, effectiveSourceType, entry.AdjustmentOf, req.EntryDate)
	if err != nil {
		return nil, err
	}
	adjustmentCategoryCode, adjustmentCategoryLabel, err := resolveJournalAdjustmentCategory(effectiveSourceType, adjustmentOf, req.AdjustmentCategoryCode)
	if err != nil {
		return nil, err
	}
	totalDebit, totalCredit, err := validateJournalLines(s.db, req.Lines, shouldDisallowCashBankLinkedAccounts(effectiveSourceType, adjustmentOf, false))
	if err != nil {
		return nil, err
	}

	return &entry, s.db.Transaction(func(tx *gorm.DB) error {
		if strings.TrimSpace(entry.SourceType) == "" {
			entry.SourceType = models.SSOTSourceTypeManual
		}
		if requiresManualJournalApproval(entry.SourceType, entry.AdjustmentOf) {
			entry.IsAutoGenerated = false
			entry.SourceID = nil
		}

		// Update header
		entry.EntryDate = req.EntryDate
		entry.Description = req.Description
		entry.Reference = req.Reference
		entry.Notes = req.Notes
		entry.TotalDebit = totalDebit
		entry.TotalCredit = totalCredit
		entry.AdjustmentCategoryCode = adjustmentCategoryCode
		entry.AdjustmentCategoryLabel = adjustmentCategoryLabel
		// Don't change CreatedBy, but maybe UpdatedAt is handled by GORM

		if err := tx.Save(&entry).Error; err != nil {
			return err
		}

		// Replace lines: Delete old ones
		if err := tx.Where("journal_id = ?", entry.ID).Delete(&models.SSOTJournalLine{}).Error; err != nil {
			return err
		}

		// Create new lines
		for i, l := range req.Lines {
			line := &models.SSOTJournalLine{
				JournalID:    entry.ID,
				AccountID:    l.AccountID,
				LineNumber:   i + 1,
				Description:  l.Description,
				DebitAmount:  l.DebitAmount,
				CreditAmount: l.CreditAmount,
			}
			if err := tx.Create(line).Error; err != nil {
				return err
			}
		}
		return nil
	})
}

