package services

import (
	"context"
	"testing"
	"time"

	"app-sistem-akuntansi/models"

	"github.com/shopspring/decimal"
)

func TestGetPurchaseRelatedJournalEntriesIncludesAdjustments(t *testing.T) {
	db := newPurchaseJournalSSOTTestDB(t)
	service := NewUnifiedJournalService(db)
	adapter := NewPurchaseSSOTJournalAdapter(db, service, nil, nil)

	account := createSSOTTestAccount(t, db, "1103-001", "PERSEDIAAN BARANG DAGANG", models.AccountTypeAsset, models.CategoryCurrentAsset)
	purchaseID := uint64(77)
	userID := uint64(1)
	baseTime := time.Date(2026, time.April, 16, 8, 0, 0, 0, time.UTC)

	entries := []models.SSOTJournalEntry{
		{
			EntryNumber:     "PURCHASE-77-1",
			SourceType:      models.SSOTSourceTypePurchase,
			SourceID:        &purchaseID,
			SourceCode:      "PO/2026/04/0077",
			EntryDate:       baseTime,
			Description:     "Purchase journal",
			Reference:       "PO/2026/04/0077",
			TotalDebit:      decimal.RequireFromString("100.00"),
			TotalCredit:     decimal.RequireFromString("100.00"),
			Status:          models.SSOTStatusPosted,
			IsBalanced:      true,
			IsAutoGenerated: true,
			CreatedBy:       userID,
		},
		{
			EntryNumber:     "PAYMENT-77-1",
			SourceType:      models.SSOTSourceTypePayment,
			SourceID:        &purchaseID,
			SourceCode:      "PO/2026/04/0077",
			EntryDate:       baseTime.Add(1 * time.Hour),
			Description:     "Payment journal",
			Reference:       "PAY/2026/04/0077",
			TotalDebit:      decimal.RequireFromString("100.00"),
			TotalCredit:     decimal.RequireFromString("100.00"),
			Status:          models.SSOTStatusPosted,
			IsBalanced:      true,
			IsAutoGenerated: true,
			CreatedBy:       userID,
		},
		{
			EntryNumber:     "ADJUSTMENT-77-1",
			SourceType:      models.SSOTSourceTypeAdjustment,
			SourceID:        &purchaseID,
			SourceCode:      "PO/2026/04/0077",
			EntryDate:       baseTime.Add(2 * time.Hour),
			Description:     "Backorder HPP settlement",
			Reference:       "BO-HPP-PO/2026/04/0077",
			Notes:           salesBackorderSettlementNotes,
			TotalDebit:      decimal.RequireFromString("25.00"),
			TotalCredit:     decimal.RequireFromString("25.00"),
			Status:          models.SSOTStatusPosted,
			IsBalanced:      true,
			IsAutoGenerated: true,
			CreatedBy:       userID,
		},
	}
	if err := db.Create(&entries).Error; err != nil {
		t.Fatalf("seed journal entries: %v", err)
	}

	lines := []models.SSOTJournalLine{
		{
			JournalID:    entries[0].ID,
			AccountID:    uint64(account.ID),
			LineNumber:   1,
			Description:  "purchase line",
			DebitAmount:  decimal.RequireFromString("100.00"),
			CreditAmount: decimal.Zero,
		},
		{
			JournalID:    entries[1].ID,
			AccountID:    uint64(account.ID),
			LineNumber:   1,
			Description:  "payment line",
			DebitAmount:  decimal.RequireFromString("100.00"),
			CreditAmount: decimal.Zero,
		},
		{
			JournalID:    entries[2].ID,
			AccountID:    uint64(account.ID),
			LineNumber:   1,
			Description:  "adjustment line",
			DebitAmount:  decimal.RequireFromString("25.00"),
			CreditAmount: decimal.Zero,
		},
	}
	if err := db.Create(&lines).Error; err != nil {
		t.Fatalf("seed journal lines: %v", err)
	}

	related, err := adapter.GetPurchaseRelatedJournalEntries(context.Background(), purchaseID, true)
	if err != nil {
		t.Fatalf("get purchase related journal entries: %v", err)
	}

	if len(related) != 3 {
		t.Fatalf("expected 3 related journal entries, got %d", len(related))
	}
	if related[0].SourceType != models.SSOTSourceTypeAdjustment {
		t.Fatalf("expected latest related journal to be adjustment, got %s", related[0].SourceType)
	}

	found := map[string]bool{}
	for _, entry := range related {
		found[entry.SourceType] = true
	}
	for _, sourceType := range []string{
		models.SSOTSourceTypePurchase,
		models.SSOTSourceTypePayment,
		models.SSOTSourceTypeAdjustment,
	} {
		if !found[sourceType] {
			t.Fatalf("expected related journal list to include %s entry", sourceType)
		}
	}
}
